def draw_face(cv, eyes=None, mouth=None):
    """顔を描く。eyes と mouth に名前を渡すとその行が差し替わる"""
    rows = list(FACE)
    if eyes:
        rows[EYE_Y:EYE_Y + EYE_H] = EYES[eyes]
    if mouth:
        rows[MOUTH_Y:MOUTH_Y + MOUTH_H] = MOUTH[mouth]
    cv.sprite(FACE_X, 0, rows)


# (目, 何フレーム出すか)。半目を挟まないと、まばたきが一瞬すぎて見えない
BLINK = (("half", 4), ("shut", 6), ("half", 4))
WINK = (("half", 4), ("wink", 18), ("half", 4))

EYE_CAM = EYE_Y - 1      # 目が窓のまんなかに来るカメラの位置
PAN = 0.4                # カメラの速さ(ドット/フレーム)


def main(m):
    cv = Buffer(FH)

    def shot(cam, eyes=None, mouth=None):
        cv.cls()
        draw_face(cv, eyes, mouth)
        m.show(cv, int(round(cam)))
        if not m.tick():
            return False
        return not m.any_pressed()

    def hold(cam, n, eyes=None, mouth=None):
        for _ in range(n):
            if not shot(cam, eyes, mouth):
                return False
        return True

    def pan(start, stop, mouth=None):
        """startからstopまで、PANずつカメラを動かす"""
        step = PAN if stop > start else -PAN
        cam = float(start)
        while (cam < stop) if step > 0 else (cam > stop):
            if not shot(cam, mouth=mouth):
                return False
            cam += step
        return True

    def play(table, mouth=None):
        for eyes, n in table:
            if not hold(EYE_CAM, n, eyes, mouth):
                return False
        return True

    # 1) 髪のてっぺんから目まで降りる
    if not pan(-3, EYE_CAM):
        return
    # 2) 目の高さで止まって、まばたきを2回
    for _ in range(2):
        if not hold(EYE_CAM, 16) or not play(BLINK):
            return
    if not hold(EYE_CAM, 12):
        return
    # 3) 口もとから肩まで降りる
    if not pan(EYE_CAM, FH - 7, mouth="smile"):
        return
    if not hold(FH - 7, 20, mouth="smile"):
        return
    # 4) 目まで戻ってウィンク
    if not pan(FH - 7, EYE_CAM, mouth="smile"):
        return
    if not play(WINK, mouth="smile"):
        return
    hold(EYE_CAM, 20, mouth="smile")
